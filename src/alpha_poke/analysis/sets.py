"""L0 of the layered archetype representation: per-species set archetypes mined from replays.

Replays reveal only part of each set (about half the moves, ~45% of items), so a set
archetype is modelled as a latent class with its own categorical distributions over item,
ability, tera type and moves. Each appearance of a species is generated by one class; only
the revealed atoms contribute to its likelihood (unrevealed != absent), so missing data is
handled naturally. Fit by EM per species, K chosen by BIC.

    p(appearance) = sum_k pi_k * phi_item[k, i] * phi_ability[k, a] * phi_tera[k, t]
                                * prod_{revealed moves m} phi_move[k, m]

Moves use a "share" distribution: 4 * phi_move[k, m] (capped at 1) is a rough estimate of the
probability that the set carries move m.
"""

from collections import Counter
from dataclasses import dataclass, field

import numpy as np
import pandas as pd

ATTRS = ("item", "ability", "tera", "move")


@dataclass
class SetArchetype:
    species: str
    index: int
    weight: float  # pi_k: share of this species' appearances
    n_eff: float  # expected number of appearances in this class
    item: list[tuple[str, float]]
    ability: list[tuple[str, float]]
    tera: list[tuple[str, float]]
    moves: list[tuple[str, float]]  # (move, estimated P(carried)) sorted, top 8
    label: str = ""

    def summary(self) -> str:
        it = self.item[0][0] if self.item else "?"
        mv = " / ".join(m for m, _ in self.moves[:4])
        te = self.tera[0][0] if self.tera else "?"
        return f"{self.species} @ {it} [tera {te}]: {mv}"


@dataclass
class SpeciesSets:
    species: str
    n: int  # appearances with at least one revealed atom
    k: int
    bic: float
    sets: list[SetArchetype]
    vocab: dict[str, list[str]] = field(repr=False, default_factory=dict)
    params: dict[str, np.ndarray] = field(repr=False, default_factory=dict)

    def posterior(self, item=None, ability=None, tera=None, moves=()) -> np.ndarray:
        """Class posterior given (partial) revealed info, e.g. during a battle."""
        lp = np.log(self.params["pi"]).copy()
        for attr, val in (("item", item), ("ability", ability), ("tera", tera)):
            if isinstance(val, str) and val in self.vocab[attr]:
                lp += np.log(self.params[attr][:, self.vocab[attr].index(val)])
        for mv in moves:
            if mv in self.vocab["move"]:
                lp += np.log(self.params["move"][:, self.vocab["move"].index(mv)])
        p = np.exp(lp - lp.max())
        return p / p.sum()


def _encode(rows: pd.DataFrame, min_count: int):
    vals = {
        "item": [v if isinstance(v, str) else None for v in rows.item],
        "ability": [v if isinstance(v, str) else None for v in rows.ability],
        "tera": [v if isinstance(v, str) else None for v in rows.tera_type],
        "move": [[m for m in (s or "").split("|") if m] for s in rows.moves],
    }
    vocab, mats = {}, {}
    for attr in ATTRS:
        if attr == "move":
            c = Counter(m for ms in vals[attr] for m in ms)
        else:
            c = Counter(v for v in vals[attr] if v)
        vocab[attr] = [k for k, n in c.most_common() if n >= min_count]
        idx = {k: i for i, k in enumerate(vocab[attr])}
        x = np.zeros((len(rows), max(len(vocab[attr]), 1)))
        for r, v in enumerate(vals[attr]):
            for item in v if attr == "move" else ([v] if v else []):
                if item in idx:
                    x[r, idx[item]] += 1
        mats[attr] = x
    keep = sum(mats[a].sum(1) for a in ATTRS) > 0
    return vocab, {a: mats[a][keep] for a in ATTRS}


def _em(mats, k: int, rng, iters: int = 200, alpha: float = 0.5):
    n = next(iter(mats.values())).shape[0]
    resp = rng.dirichlet(np.ones(k), size=n)
    ll_old = -np.inf
    for _ in range(iters):
        pi = resp.mean(0) + 1e-12
        phi = {}
        for a, x in mats.items():
            w = resp.T @ x + alpha
            phi[a] = w / w.sum(1, keepdims=True)
        lp = np.log(pi)[None, :] + sum(x @ np.log(phi[a]).T for a, x in mats.items())
        mx = lp.max(1, keepdims=True)
        lse = mx + np.log(np.exp(lp - mx).sum(1, keepdims=True))
        resp = np.exp(lp - lse)
        ll = float(lse.sum())
        if ll - ll_old < 1e-4 * abs(ll):
            break
        ll_old = ll
    return ll, pi, phi, resp


def fit_species(
    rows: pd.DataFrame,
    species: str,
    max_k: int = 6,
    min_count: int = 5,
    min_weight: float = 0.05,
    restarts: int = 4,
    seed: int = 0,
) -> SpeciesSets | None:
    vocab, mats = _encode(rows, min_count)
    n = next(iter(mats.values())).shape[0]
    if n < 50:
        return None
    rng = np.random.default_rng(seed)
    best = None
    for k in range(1, max_k + 1):
        fits = [_em(mats, k, rng) for _ in range(restarts if k > 1 else 1)]
        ll, pi, phi, resp = max(fits, key=lambda f: f[0])
        if k > 1 and pi.min() < min_weight:  # a negligible class: stop growing K
            break
        n_params = (k - 1) + k * sum(max(len(vocab[a]), 1) - 1 for a in ATTRS)
        bic = -2 * ll + n_params * np.log(n)
        if best is None or bic < best[0]:
            best = (bic, k, pi, phi, resp)
    bic, k, pi, phi, resp = best
    order = np.argsort(-pi)
    sets = []
    for rank, j in enumerate(order):

        def top(attr, j=j, cap=None, n_top=3):
            p = phi[attr][j]
            idx = np.argsort(-p)[:n_top]
            return [
                (vocab[attr][i], float(min(4 * p[i], 1.0) if cap else p[i]))
                for i in idx
                if i < len(vocab[attr])
            ]

        sets.append(
            SetArchetype(
                species=species,
                index=rank,
                weight=float(pi[j]),
                n_eff=float(resp[:, j].sum()),
                item=top("item"),
                ability=top("ability", n_top=2),
                tera=top("tera"),
                moves=top("move", cap=True, n_top=8),
            )
        )
    params = {"pi": pi[order]} | {a: phi[a][order] for a in ATTRS}
    return SpeciesSets(species, n, k, float(bic), sets, vocab, params)


def mine_sets(mons: pd.DataFrame, min_appearances: int = 150, **kw) -> dict[str, SpeciesSets]:
    brought = mons[mons.brought]
    counts = brought.species.value_counts()
    out = {}
    for sp in counts[counts >= min_appearances].index:
        res = fit_species(brought[brought.species == sp], sp, **kw)
        if res:
            out[sp] = res
    return out
